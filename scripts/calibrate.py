"""Calibrate flag_at on set A genuine sessions (G9): python scripts/calibrate.py --sessions data/sessions

Re-runs analyze() on every labelled set A session. For each voting check, flag_at becomes just above the 97.5th
percentile of its risk on genuine sessions (usable results only), so at most 1 genuine session in 40 is flagged
(a result flags when risk >= flag_at). With fewer than 20 genuine usable results the provisional value stays, and the
report says so. Writes server/pulselens/analysis/thresholds.calibrated.yaml: {check_id: {flag_at, n_genuine, source}}.

Never reads set B: sessions are filtered to set A first, and a set B session left after that is a programming error
that stops the script.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "server"))

from pulselens.analysis import analyze, specs  # noqa: E402
from pulselens.analysis.thresholds import CALIBRATED, PROVISIONAL, Thresholds  # noqa: E402
from pulselens.bundle import load_bundle  # noqa: E402
from pulselens.contracts import CheckResult  # noqa: E402

PERCENTILE = 97.5
MIN_GENUINE = 20


@dataclass(frozen=True)
class Row:
    session_id: str
    set: str
    kind: str
    results: list[CheckResult]


def set_a(rows: list[Row]) -> list[Row]:
    """Set A only. Raises on a set B row left after the filter (it would mean the filter is broken)."""
    kept = [r for r in rows if r.set == "A"]
    if any(r.set == "B" for r in kept):
        raise SystemExit("calibrate: a set B session got past the set A filter")
    return kept


def calibrate(rows: list[Row], provisional: Thresholds) -> tuple[dict[str, dict], list[tuple[str, int, float, str]]]:
    """(the calibrated.yaml content, report rows (check_id, n_genuine, flag_at, source)) from set A rows."""
    genuine = [r for r in set_a(rows) if r.kind == "genuine"]
    out, report = {}, []
    for spec in specs.ALL:
        if spec.never_flags:
            continue
        risks = [res.risk for r in genuine for res in r.results
                 if res.check_id == spec.check_id and res.status == "usable" and res.risk is not None]
        if len(risks) < MIN_GENUINE:
            report.append((spec.check_id, len(risks), provisional.flag_at(spec.check_id), "provisional"))
            continue
        flag_at = float(np.nextafter(np.percentile(risks, PERCENTILE), np.inf))
        out[spec.check_id] = {"flag_at": flag_at, "n_genuine": len(risks), "source": "calibrated"}
        report.append((spec.check_id, len(risks), flag_at, "calibrated"))
    return out, report


def load_rows(sessions: Path) -> list[Row]:
    """Labelled set A sessions under `sessions`, analysed afresh. Set B folders are skipped before analysis."""
    rows = []
    for path in sorted(p for p in sessions.iterdir() if p.is_dir()):
        label = load_bundle(path).label
        if label is None or label.set != "A":
            continue
        rows.append(Row(path.name, label.set, label.kind, analyze(path)))
    return rows


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sessions", type=Path, default=Path("data/sessions"))
    ap.add_argument("--out", type=Path, default=CALIBRATED)
    args = ap.parse_args(argv)
    if not args.sessions.is_dir():
        print(f"{args.sessions} is not a directory", file=sys.stderr)
        return 2
    rows = load_rows(args.sessions)
    calibrated, report = calibrate(rows, Thresholds(yaml.safe_load(PROVISIONAL.read_text(encoding="utf-8"))))
    n_genuine = sum(r.kind == "genuine" for r in rows)
    print(f"{len(rows)} set A sessions, {n_genuine} genuine\n")
    print("| check_id | n genuine | flag_at | source |\n|---|---|---|---|")
    for check_id, n, flag_at, source in report:
        print(f"| {check_id} | {n} | {flag_at:.3f} | {source} |")
    args.out.write_text("# Generated by scripts/calibrate.py from set A genuine sessions. Do not edit by hand.\n"
                        + yaml.safe_dump(calibrated, sort_keys=True), encoding="utf-8")
    print(f"\nwrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
